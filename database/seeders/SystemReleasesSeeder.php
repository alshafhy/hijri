    public function run(): void
    {
        foreach (self::releases() as [$version, $date, $features]) {
            if (SystemRelease::query()->where('version_number', $version)->exists()) {
                continue;
            }

            $release = SystemRelease::query()->create(['version_number' => $version, 'release_date' => $date]);
            foreach ($features as $order => $title) {
                $release->features()->create(['title' => $title, 'description' => '', 'feature_order' => $order + 1]);
            }
        }
    }

