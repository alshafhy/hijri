<h2>البند الأول: صفة التمهيد</h2>
<p>يعتبر التمهيد السابق جزءاً لا يتجزأ من هذا العقد، ولا يجوز التعديل أو التغيير فيه إلا بموافقة الطرفين الكتابية المسبقة، ويلتزم كل طرف باحترام بنود العقد والتقيد بها.</p>

<h2>البند الثاني: مصطلحات العقد</h2>
<ul>
  <li><strong>النظام:</strong> نظام المقيّمين المعتمدين. <strong>اللائحة:</strong> اللائحة التنفيذية للنظام. <strong>القواعد:</strong> قواعد سلوك مهنة التقييم وآدابها.</li>
  <li><strong>الهيئة:</strong> الهيئة السعودية للمقيّمين المعتمدين.</li>
  <li><strong>تقرير التقييم:</strong> الوثيقة التي يصدرها المقيم المعتمد لعملائه متضمّنةً نتيجة التقييم ومتوافقةً مع معايير التقييم المعتمدة.</li>
  <li><strong>العميل:</strong> الشخص ذو الصفة الطبيعية أو الاعتبارية الذي يكلّف المقيم بأداء مهمة التقييم.</li>
</ul>

